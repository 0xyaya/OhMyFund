"""Bundle all saved Tokens equities and variants for the offline Screener."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=json.loads((root/'data/tokens-screener.json').read_text())
path=root/'docs/designs/stocks-data.js'
old=json.loads(path.read_text().split('window.STOCK_SNAPSHOT = ',1)[1].rstrip(';\n')) if path.exists() else {}
cache={}
logos={row["assetId"]:row.get("localLogo") for row in old.get("stocks",[]) if row.get("localLogo")}
for row in old.get('stocks',[]):
 for v in row.get('variants',[row]):
  cache[v['mint']]=v
rows=[]
for asset in source['assets']:
 if asset.get('category') not in ['equity','crypto','etf','commodity']:continue
 variants=[]
 for v in asset.get('variants',[]):
  if not v.get('mint'):continue
  issuer=v.get('issuer') or v.get('label') or 'Issuer unspecified'
  if 'Backpack Securities' in v.get('name','') and not v.get('issuer'):issuer='Backpack Securities'
  cached=cache.get(v['mint'],{})
  variants.append({'assetId':asset['assetId'],'name':asset.get('name') or asset['assetId'],'symbol':asset.get('symbol') or v.get('symbol') or asset['assetId'],'tokenSymbol':v.get('symbol'),'tokenName':v.get('name'),'mint':v['mint'],'issuer':issuer,'sourceIssuer':v.get('issuer'),'category':asset['category'],'variantId':v.get('variantId'),'market':v.get('market'),'advisory':v.get('advisory'),'candles':cached.get('candles',[]),'chartSource':cached.get('chartSource'),'chartStatus':cached.get('chartStatus'),'chartError':cached.get('chartError'),'chartFrom':cached.get('chartFrom'),'chartTo':cached.get('chartTo'),'matchEvidence':'Tokens issuer or variant label'})
 primary=(asset.get('primaryVariant') or {}).get('mint')
 selected=next((v for v in variants if v['mint']==primary),variants[0] if variants else None)
 if selected:rows.append({**selected,'variants':variants,'localLogo':logos.get(asset['assetId'])})
 else:raise ValueError('Equity has no mint: '+asset['assetId'])
bundle={'source':source['source'],'retrievedAt':source['retrievedAt'],'chartFrom':old.get('chartFrom'),'chartTo':old.get('chartTo'),'stocks':rows}
path.write_text('// Generated by scripts/build-stock-preview.py. Saved snapshot, not live.\nwindow.STOCK_SNAPSHOT = '+json.dumps(bundle,separators=(',',':')).replace('<','\\u003c')+';\n')
print(f'{len(rows)} equities; {sum(len(r["variants"]) for r in rows)} variants; {len(cache)} cached mint charts')
